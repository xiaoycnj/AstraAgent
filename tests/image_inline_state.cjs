/* Pure event-state regression; no model service or browser required. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../web/assets/js/features/images.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('const inlineImageTools='), source.indexOf('const inlineImageViews=')), context);
const update = context.updateInlineImageRun;
const draft = {}, other = {};
const a = 'a'.repeat(32), b = 'b'.repeat(32);
const event = (type, id, result) => ({type, name: 'generate_image', tool_call_id: id, result});
update(draft, event('tool_start', 'one'));
update(draft, event('tool_start', 'two'));
assert.equal(draft.imagePending.size, 2);
assert.equal(other.imagePending, undefined);
update(draft, event('tool', 'one', {ok:true, attachment:{kind:'image', id:a}}));
assert.equal(draft.imagePending.size, 1);
update(draft, event('step_reused', 'one', {ok:true, attachment:{kind:'image', id:a}}));
assert.equal(draft.generated_attachment_ids.length, 1);
update(draft, event('tool', 'two', {ok:false, attachment:{kind:'image', id:b}}));
assert.equal(draft.generated_attachment_ids.length, 1);
assert.equal(draft.imagePending.size, 0);
update(draft, event('tool_start', 'three'));
update(draft, {type:'cancelled'});
assert.equal(draft.imagePending.size, 0);
update(draft, {type:'done', generated_attachment_ids:[a,b,a,'bad']});
assert.equal(draft.generated_attachment_ids.join(','), [a,b].join(','));
assert.equal(other.generated_attachment_ids, undefined);
update(other, event('tool_start', 'failure'));
update(other, {type:'error'});
assert.equal(other.imagePending.size, 0);
assert.equal(update(other, {type:'tool_start', name:'list_image_models'}), false);
console.log('PASS: image pending, ordering, replay dedupe, failure, cancellation and draft isolation');
